library(shinyOAuthDB)
source(testthat::test_path("..", "..", "tests", "testthat", "helper-authorization.R"))
fixture <- Sys.getenv("OAUTHDB_CRATEDB_FIXTURE_OUT")
tokens <- jsonlite::read_json(file.path(fixture, "tokens.json"))
ca <- file.path(fixture, "fixture-ca.pem")
endpoint <- Sys.getenv("OAUTHDB_CRATEDB_ENDPOINT")

test_that("CrateDB authenticates real visitor JWTs and enforces user privileges", {
  retained <- NULL
  odb_test_domain(function(session) {
    a <- odb_test_authorization(session)
    b <- odb_test_authorization(session, id = "B")
    a$token(a$make_token(tokens$a))
    b$token(b$make_token(tokens$b))
    selected <- shiny::reactiveVal(a$connection)
    api <- oauth_db_cratedb_api(selected, endpoint, schema = "doc", ca_bundle = ca)
    expect_identical(api$query("SELECT current_user AS username")$username, "alice")
    result <- api$query("SELECT id, amount, flag, tags FROM orders")
    expect_identical(result$id, "9007199254740993")
    expect_identical(result$amount, "123456789012345678.123456789")
    expect_identical(result$flag, TRUE)
    expect_identical(result$tags, list(list("9007199254740993")))
    expect_equal(nrow(api$query("SELECT * FROM orders WHERE id = $1::bigint", list("9007199254740993"))), 1L)
    expect_equal(nrow(api$query("SELECT * FROM orders WHERE id = $1::bigint", list("0"))), 0L)
    a$token(a$make_token(tokens$rotated))
    expect_identical(api$query("SELECT current_user AS username")$username, "alice")
    selected(b$connection)
    expect_identical(api$query("SELECT current_user AS username")$username, "bob")
    expect_error(api$query("SELECT * FROM alice_only"), class = "shinyOAuthDB_request_failed")
    expect_error(api$execute("INSERT INTO orders (id) VALUES (2)"), class = "shinyOAuthDB_request_failed")
    selected(a$connection)
    expect_identical(api$execute("INSERT INTO orders (id, counter) VALUES ($1, 0)", list(2L)), 1)
    api$execute("REFRESH TABLE orders")
    expect_identical(api$query("SELECT count(*) AS n FROM orders")$n, "2")
    expect_error(api$execute("UPDATE orders SET counter = counter + 1 WHERE id = 2 /* fixture-drop */"), class = "shinyOAuthDB_request_failed")
    api$execute("REFRESH TABLE orders")
    expect_identical(api$query("SELECT counter AS n FROM orders WHERE id = 2")$n, 1)
    for (bad in list(tokens$audience, tokens$expired, paste0(tokens$a, "invalid"))) {
      a$token(a$make_token(bad))
      error <- tryCatch(api$query("SELECT 1"), error = identity)
      expect_s3_class(error, "shinyOAuthDB_request_failed")
      expect_false(grepl(bad, conditionMessage(error), fixed = TRUE))
    }
    a$token(a$make_token(tokens$a))
    timeout <- oauth_db_cratedb_api(selected, endpoint, timeout = 0.2, ca_bundle = ca)
    expect_error(timeout$query("SELECT 1 /* fixture-delay */"), class = "shinyOAuthDB_timeout")
    untrusted <- oauth_db_cratedb_api(selected, endpoint)
    expect_error(untrusted$query("SELECT 1"), class = "shinyOAuthDB_request_failed")
    mismatch <- oauth_db_cratedb_api(selected, sub("localhost", "127.0.0.1", endpoint), ca_bundle = ca)
    expect_error(mismatch$query("SELECT 1"), class = "shinyOAuthDB_request_failed")
    selected(NULL)
    expect_error(api$query("SELECT 1"), class = "shiny.silent.error")
    retained <<- api
  })
  odb_test_domain(function(session) {
    expect_error(retained$query("SELECT 1"), class = "shinyOAuthDB_authorization_unavailable")
  })
})
